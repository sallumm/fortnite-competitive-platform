import { historicalSeed } from "./historical-seed.mjs";
// Regenerate only the incremental Training Maxing catalog; no database connection.
import fs from "node:fs";
import ts from "typescript";
const module = { exports: {} };
const compiled = ts.transpileModule(
  fs.readFileSync("src/lib/training-catalog.ts", "utf8"),
  { compilerOptions: { module: ts.ModuleKind.CommonJS } },
).outputText;
new Function("exports", "module", compiled)(module.exports, module);
const sql = (value) =>
  value == null ? "NULL" : "'" + String(value).replaceAll("'", "''") + "'";
const columns = [
  "id",
  "title",
  "creator",
  "map_code",
  "category",
  "mode",
  "level",
  "description",
  "instructions",
  "metric",
  "source_url",
  "verified_at",
];
const rows = module.exports.trainingCatalog.map(
  (e) =>
    `(${columns.map((k) => sql(e[k])).join(",")},true,ARRAY[${e.categories.map(sql).join(",")}],ARRAY[${e.tags.map(sql).join(",")}],${sql(JSON.stringify(e.measurement))}::jsonb,${sql(e.video_url)})`,
);
historicalSeed(
  "supabase/migrations/202610100008_training_seed.sql",
  `-- Generated by node scripts/training-seed.mjs. Original editorial protocols.\n-- Listings verified 2026-10-10; not tested inside Fortnite.\ninsert into public.exercises(${columns.join(",")},published,categories,tags,measurement,video_url) values\n${rows.join(",\n")}\non conflict(id) do nothing;\n`,
);
