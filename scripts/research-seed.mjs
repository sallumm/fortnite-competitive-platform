// Deterministic offline generator. Never connects to a database or changes historical seeds.
import fs from "node:fs";
import ts from "typescript";
const trainingModule = { exports: {} };
new Function(
  "exports",
  "module",
  ts.transpileModule(fs.readFileSync("src/lib/training-catalog.ts", "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText,
)(trainingModule.exports, trainingModule);
const existingExercises = trainingModule.exports.trainingCatalog;
const read = (name) =>
  JSON.parse(fs.readFileSync(`src/data/${name}.json`, "utf8"));
const corpus = read("training-knowledge"),
  metadata = read("exercise-research"),
  exercises = read("research-exercises");
const quote = (x) =>
  x === null
    ? "NULL"
    : typeof x === "boolean"
      ? String(x)
      : `'${String(x).replaceAll("'", "''")}'`;
const json = (x) => quote(JSON.stringify(x)) + "::jsonb";
const lines = [
  "-- Generated by node scripts/research-seed.mjs. Research corpus 2026-10-10.1.",
  "-- No historical result, exercise metric protocol or private record is changed.",
];
for (const [key, kind] of [
  ["references", "reference"],
  ["competencies", "competency"],
  ["principles", "principle"],
  ["paths", "path"],
])
  for (const row of corpus[key])
    lines.push(
      `insert into public.training_knowledge(id,kind,version,content) values(${quote(row.id)},${quote(kind)},${quote(corpus.version)},${json(row)}) on conflict(kind,id) do nothing;`,
    );
for (const [id, value] of Object.entries(metadata.exercises)) {
  const original = existingExercises.find((e) => e.id === id);
  if (!original) throw Error(`Unknown exercise ${id}`);
  // Do not attach a reviewed protocol to an exercise an editor already changed.
  lines.push(
    `update public.exercises set research=${json({ ...metadata.defaults, ...value })} where id=${quote(id)} and research is null and instructions=${quote(original.instructions)} and source_url=${quote(original.source_url)} and mode=${quote(original.mode)} and measurement=${json(original.measurement)};`,
  );
}
for (const row of exercises) {
  const keys = Object.keys(row);
  lines.push(
    `insert into public.exercises(${keys.join(",")}) values(${keys.map((k) => (["research", "measurement"].includes(k) ? json(row[k]) : Array.isArray(row[k]) ? `ARRAY[${row[k].map(quote).join(",")}]` : quote(row[k]))).join(",")}) on conflict(id) do nothing;`,
  );
}
const output = lines.join("\n") + "\n";
const target = "supabase/migrations/202610100011_training_research_seed.sql";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== output)
    throw Error("Research seed out of sync");
} else fs.writeFileSync(target, output);

const index =
  JSON.stringify(
    {
      competencies: corpus.competencies.map(({ id, mode }) => ({ id, mode })),
      references: corpus.references.map(({ id, access }) => ({ id, access })),
    },
    null,
    2,
  ) + "\n";
const indexPath = "src/data/training-knowledge-index.json";
if (process.argv.includes("--check")) {
  if (fs.readFileSync(indexPath, "utf8") !== index)
    throw Error("Research validation index out of sync");
} else fs.writeFileSync(indexPath, index);
